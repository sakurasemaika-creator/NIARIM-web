import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const root = path.resolve(import.meta.dirname, "..");
const publicDir = path.join(root, "public");
const jsDir = path.join(publicDir, "js");
const seoOutDir = path.join(root, "src", "generated");
const seoOutFile = path.join(seoOutDir, "seo-i18n.js");
const pageBundleDir = path.join(jsDir, "generated");
const langs = ["ja", "en", "zh-Hans", "zh-Hant", "ko", "fr", "es"];
const requiredPages = [
  "home",
  "about",
  "community",
  "contact",
  "faq",
  "features",
  "help",
  "news",
  "premium",
  "privacy",
  "terms",
];
const seo = Object.fromEntries(langs.map((lang) => [lang, {}]));
const scripts = new Map();
const loaded = new Set();

function readScript(file) {
  if (!scripts.has(file)) {
    scripts.set(file, fs.readFileSync(path.join(jsDir, file), "utf8"));
  }
  return scripts.get(file);
}

function scriptFilesFromHtml(html) {
  return Array.from(
    html.matchAll(/<script\b[^>]*\bsrc=["']\/js\/([^"']+\.js)["'][^>]*>/g),
    (match) => match[1],
  );
}

function dictionaryFilesFromHtml(html) {
  return scriptFilesFromHtml(html).filter((file) =>
    /^i18n-dict(?:-[\w-]+)?\.js$/.test(file),
  );
}

function addAttributeKeys(source, keys) {
  const normalized = source.replaceAll('\\"', '"').replaceAll("\\'", "'");

  for (const match of normalized.matchAll(
    /data-i18n(?:-html|-title|-description)?=["']([^"']+)["']/g,
  )) {
    keys.add(match[1]);
  }

  for (const match of normalized.matchAll(/data-i18n-attr=["']([^"']+)["']/g)) {
    for (const pair of match[1].split("|")) {
      const separator = pair.indexOf(":");
      if (separator !== -1) keys.add(pair.slice(separator + 1));
    }
  }

  for (const match of normalized.matchAll(
    /\.translate\([^,]+,\s*["']([^"']+)["']/g,
  )) {
    keys.add(match[1]);
  }
}

function collectPageKeys(page, html, dictionary) {
  const keys = new Set();
  addAttributeKeys(html, keys);

  const runtimeFiles = scriptFilesFromHtml(html)
    .filter(
      (file) => !/^i18n-dict(?:-[\w-]+)?\.js$/.test(file) && file !== "i18n.js",
    )
    .map((file) => {
      if (file === "main.js" && page !== "home" && page !== "features") {
        return "common-ui.js";
      }
      return file;
    });

  for (const file of new Set(runtimeFiles)) {
    const filePath = path.join(jsDir, file);
    if (!fs.existsSync(filePath)) continue;
    addAttributeKeys(readScript(file), keys);
  }

  // i18n.js reads these page metadata keys from body attributes, but keep them
  // explicitly as a guard if the static markup changes later.
  keys.add(`meta.${page}.title`);
  keys.add(`meta.${page}.description`);

  // Help search/category rendering can address help.* keys indirectly through
  // arrays, so retain the whole namespace rather than relying on literal scans.
  if (page === "help") {
    for (const key of Object.keys(dictionary.ja || {})) {
      if (key.startsWith("help.")) keys.add(key);
    }
  }

  return keys;
}

function makePageBundle(page, dictionary, keys) {
  const bundle = {};
  for (const lang of langs) {
    const table = dictionary[lang] || {};
    const fallback = dictionary.ja || {};
    bundle[lang] = {};
    for (const key of keys) {
      const value = Object.prototype.hasOwnProperty.call(table, key)
        ? table[key]
        : fallback[key];
      if (typeof value !== "undefined") bundle[lang][key] = value;
    }
  }

  const banner =
    "// Generated by tools/generate-seo-i18n.mjs. Do not edit by hand.\n";
  const body =
    '(function(){"use strict";var D=window.NIARIM_I18N_DICT||(window.NIARIM_I18N_DICT={});var B=' +
    JSON.stringify(bundle) +
    ";Object.keys(B).forEach(function(l){D[l]=Object.assign(D[l]||{},B[l]);});})();\n";
  const outFile = path.join(pageBundleDir, `i18n-${page}.js`);
  fs.writeFileSync(outFile, banner + body, "utf8");
  return {
    file: outFile,
    bytes: Buffer.byteLength(banner + body),
    keys: keys.size,
  };
}

fs.mkdirSync(pageBundleDir, { recursive: true });

const pageBundleStats = [];
for (const page of requiredPages) {
  const htmlPath =
    page === "home" ? "public/index.html" : `public/${page}/index.html`;
  const html = fs.readFileSync(path.join(root, htmlPath), "utf8");
  const window = { NIARIM_I18N_DICT: {} };
  const context = vm.createContext({ window, console });

  // Follow this page's browser order so later override dictionaries win exactly
  // as they do in the real page.
  for (const file of dictionaryFilesFromHtml(html)) {
    const code = readScript(file);
    vm.runInContext(code, context, { filename: file });
    loaded.add(file);
  }

  for (const lang of langs) {
    for (const field of ["title", "description"]) {
      const key = `meta.${page}.${field}`;
      const value = window.NIARIM_I18N_DICT[lang]?.[key];
      if (typeof value !== "string" || !value.trim()) {
        throw new Error(`Missing localized SEO key: ${lang} ${key}`);
      }
      seo[lang][key] = value;
    }
  }

  const pageKeys = collectPageKeys(page, html, window.NIARIM_I18N_DICT);
  pageBundleStats.push(makePageBundle(page, window.NIARIM_I18N_DICT, pageKeys));
}

fs.mkdirSync(seoOutDir, { recursive: true });
const banner =
  "// Generated by tools/generate-seo-i18n.mjs. Do not edit by hand.\n";
fs.writeFileSync(
  seoOutFile,
  `${banner}export const SEO_LANGS = ${JSON.stringify(langs)};\nexport const SEO_I18N = ${JSON.stringify(seo, null, 2)};\n`,
  "utf8",
);

const totalBundleBytes = pageBundleStats.reduce(
  (sum, stat) => sum + stat.bytes,
  0,
);
console.log(
  `Generated ${path.relative(root, seoOutFile)} for ${requiredPages.length} pages from ${loaded.size} dictionaries.`,
);
console.log(
  `Generated ${pageBundleStats.length} page i18n bundles (${totalBundleBytes} bytes total): ${pageBundleStats
    .map(
      (stat) =>
        `${path.basename(stat.file)}=${stat.keys} keys/${stat.bytes} bytes`,
    )
    .join(", ")}`,
);
