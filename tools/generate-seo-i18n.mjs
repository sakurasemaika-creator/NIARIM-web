import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import prettier from "prettier";

const root = path.resolve(import.meta.dirname, "..");
const publicDir = path.join(root, "public");
const jsDir = path.join(publicDir, "js");
const seoOutDir = path.join(root, "src", "generated");
const seoOutFile = path.join(seoOutDir, "seo-i18n.js");
const pageBundleDir = path.join(jsDir, "generated");
const langs = ["ja", "en", "zh-Hans", "zh-Hant", "ko", "fr", "es"];
const requiredPages = [
  "home",
  "about",
  "community",
  "contact",
  "faq",
  "features",
  "font-licenses",
  "help",
  "news",
  "opals",
  "premium",
  "privacy",
  "terms",
  "tokushoho",
];
const seo = Object.fromEntries(langs.map((lang) => [lang, {}]));
const pageTranslations = {};
const scripts = new Map();
const loaded = new Set();

function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content)
    return false;
  // Write to a temporary file and rename it, so a reader running at the
  // same time (another build or a test) never sees a half-written file.
  const temporary = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(temporary, content, "utf8");
  fs.renameSync(temporary, file);
  return true;
}

function readScript(file) {
  if (!scripts.has(file)) {
    scripts.set(file, fs.readFileSync(path.join(jsDir, file), "utf8"));
  }
  return scripts.get(file);
}

function scriptFilesFromHtml(html) {
  return Array.from(
    html.matchAll(
      /<script\b[^>]*\bsrc=["']\/js\/([^"']+?\.js)(?:[?#][^"']*)?["'][^>]*>/g,
    ),
    (match) => match[1],
  );
}

function dictionaryFilesFromHtml(html) {
  return scriptFilesFromHtml(html).filter((file) =>
    /^i18n-dict(?:-[\w-]+)?\.js$/.test(file),
  );
}

function addAttributeKeys(source, keys) {
  const normalized = source.replaceAll('\\"', '"').replaceAll("\\'", "'");

  for (const match of normalized.matchAll(
    /(?:data-i18n(?:-html|-title|-description)?|data-play-release-i18n)=["']([^"']+)["']/g,
  )) {
    keys.add(match[1]);
  }

  for (const match of normalized.matchAll(/data-i18n-attr=["']([^"']+)["']/g)) {
    for (const pair of match[1].split("|")) {
      const separator = pair.indexOf(":");
      if (separator !== -1) keys.add(pair.slice(separator + 1));
    }
  }

  for (const match of normalized.matchAll(
    /\.translate\([^,]+,\s*["']([^"']+)["']/g,
  )) {
    keys.add(match[1]);
  }
}

function collectPageKeys(page, html, dictionary) {
  const keys = new Set();
  addAttributeKeys(html, keys);

  const runtimeFiles = scriptFilesFromHtml(html)
    .filter(
      (file) => !/^i18n-dict(?:-[\w-]+)?\.js$/.test(file) && file !== "i18n.js",
    )
    .map((file) => {
      if (file === "main.js" && page !== "home" && page !== "features") {
        return "common-ui.js";
      }
      return file;
    });

  for (const file of new Set(runtimeFiles)) {
    const filePath = path.join(jsDir, file);
    if (!fs.existsSync(filePath)) continue;
    const source = readScript(file);
    addAttributeKeys(source, keys);
    // Keys a script picks at runtime (`var key = open ? "common.menuClose" :
    // "common.menuOpen"; translate(lang, key)`) are not written next to the
    // call. Any string literal in the script that names a dictionary key is
    // carried, so such labels are not left in Japanese on other languages.
    for (const match of source.matchAll(
      /["']([A-Za-z][\w-]*(?:\.[\w-]+)+)["']/g,
    )) {
      if (Object.prototype.hasOwnProperty.call(dictionary.ja || {}, match[1])) {
        keys.add(match[1]);
      }
    }
  }

  keys.add(`meta.${page}.title`);
  keys.add(`meta.${page}.description`);

  if (page === "help" || page === "contact") {
    // Both pages look up some translations by keys assembled at runtime.
    for (const key of Object.keys(dictionary.ja || {})) {
      if (key.startsWith(`${page}.`)) keys.add(key);
    }
  }

  return keys;
}

async function makePageBundle(page, dictionary, keys) {
  const bundle = {};
  for (const lang of langs) {
    const table = dictionary[lang] || {};
    const fallback = dictionary.ja || {};
    bundle[lang] = {};
    for (const key of keys) {
      const value = Object.prototype.hasOwnProperty.call(table, key)
        ? table[key]
        : fallback[key];
      if (typeof value !== "undefined") bundle[lang][key] = value;
    }
  }

  const banner =
    "// Generated by tools/generate-seo-i18n.mjs. Do not edit by hand.\n";
  const body =
    '(function(){"use strict";var D=window.NIARIM_I18N_DICT||(window.NIARIM_I18N_DICT={});var B=' +
    JSON.stringify(bundle) +
    ";Object.keys(B).forEach(function(l){D[l]=Object.assign(D[l]||{},B[l]);});})();\n";
  const content = await prettier.format(banner + body, { parser: "babel" });
  const outFile = path.join(pageBundleDir, `i18n-${page}.js`);
  writeIfChanged(outFile, content);

  // One file per language: the Worker gives a page only the language it is
  // shown in (about a seventh of the bytes). Another language is fetched by
  // i18n.js when the visitor picks it in the language menu. Keys already in
  // the table were put there by scripts that ran after the page's bundle
  // (i18n-dict-ai-trust.js, user-request-fixes.js), so they keep precedence,
  // as they had over the bundle with every language.
  let languageBytes = 0;
  for (const lang of langs) {
    const languageBody =
      '(function(){"use strict";var D=window.NIARIM_I18N_DICT||(window.NIARIM_I18N_DICT={});var L=' +
      JSON.stringify(lang) +
      ";D[L]=Object.assign(" +
      JSON.stringify(bundle[lang]) +
      ",D[L]);var P=window.NIARIM_I18N_PAGE_BUNDLE||(window.NIARIM_I18N_PAGE_BUNDLE={page:" +
      JSON.stringify(page) +
      ",loaded:{}});P.loaded[L]=true;})();\n";
    // Served as is: one line of JSON, without the layout a formatter adds.
    const languageContent = banner + languageBody;
    writeIfChanged(
      path.join(pageBundleDir, `i18n-${page}.${lang}.js`),
      languageContent,
    );
    if (lang === "ja") languageBytes = Buffer.byteLength(languageContent);
  }
  return {
    file: outFile,
    bytes: Buffer.byteLength(content),
    languageBytes,
    keys: keys.size,
  };
}

// The page's runtime script exactly as the page asks for it (with its ?v=),
// so the Worker's <link rel="preload"> is the same request and not a second
// download of the same file.
function runtimeScriptOf(html) {
  const match = html.match(
    /<script\b[^>]*\bsrc=["'](\/js\/(?:main|common-ui)\.js(?:[?#][^"']*)?)["']/,
  );
  return match ? match[1] : null;
}

fs.mkdirSync(pageBundleDir, { recursive: true });

const pageBundleStats = [];
const pageRuntime = {};
for (const page of requiredPages) {
  const htmlPath =
    page === "home" ? "public/index.html" : `public/${page}/index.html`;
  const html = fs.readFileSync(path.join(root, htmlPath), "utf8");
  const window = { NIARIM_I18N_DICT: {} };
  const context = vm.createContext({ window, console });

  for (const file of dictionaryFilesFromHtml(html)) {
    const code = readScript(file);
    vm.runInContext(code, context, { filename: file });
    loaded.add(file);
  }

  for (const lang of langs) {
    for (const field of ["title", "description"]) {
      const key = `meta.${page}.${field}`;
      const sourceKey = page === "opals" ? `coins.meta.${field}` : key;
      const value = window.NIARIM_I18N_DICT[lang]?.[sourceKey];
      if (typeof value !== "string" || !value.trim()) {
        throw new Error(`Missing localized SEO key: ${lang} ${key}`);
      }
      seo[lang][key] = value;
    }
  }

  const htmlKeys = new Set();
  addAttributeKeys(html, htmlKeys);
  const dictionary = window.NIARIM_I18N_DICT;
  pageTranslations[page] = Object.fromEntries(
    langs.map((lang) => {
      const topics =
        page === "help"
          ? JSON.parse(
              fs.readFileSync(
                path.join(jsDir, "help-topics", `${lang}.json`),
                "utf8",
              ),
            )
          : {};
      return [
        lang,
        Object.fromEntries(
          [...htmlKeys].flatMap((key) => {
            const value =
              topics[key] ?? dictionary[lang]?.[key] ?? dictionary.ja?.[key];
            return typeof value === "string" ? [[key, value]] : [];
          }),
        ),
      ];
    }),
  );
  pageRuntime[page] = runtimeScriptOf(html);
  const pageKeys = collectPageKeys(page, html, dictionary);
  pageBundleStats.push(await makePageBundle(page, dictionary, pageKeys));
}

fs.mkdirSync(seoOutDir, { recursive: true });
const banner =
  "// Generated by tools/generate-seo-i18n.mjs. Do not edit by hand.\n";
const seoContent = await prettier.format(
  `${banner}export const SEO_LANGS = ${JSON.stringify(langs)};\nexport const SEO_I18N = ${JSON.stringify(seo, null, 2)};\nexport const PAGE_TRANSLATIONS = ${JSON.stringify(pageTranslations)};\nexport const PAGE_RUNTIME = ${JSON.stringify(pageRuntime, null, 2)};\n`,
  { parser: "babel" },
);
writeIfChanged(seoOutFile, seoContent);

const totalBundleBytes = pageBundleStats.reduce(
  (sum, stat) => sum + stat.bytes,
  0,
);
console.log(
  `Generated ${path.relative(root, seoOutFile)} for ${requiredPages.length} pages from ${loaded.size} dictionaries.`,
);
console.log(
  `Generated ${pageBundleStats.length} page i18n bundles (${totalBundleBytes} bytes total): ${pageBundleStats
    .map(
      (stat) =>
        `${path.basename(stat.file)}=${stat.keys} keys/${stat.bytes} bytes (ja alone ${stat.languageBytes})`,
    )
    .join(", ")}`,
);
